"""Per-user behavioural history, persisted in SQLite.

Every account owns rows in user_segments and user_notifications. A brand-new account gets a
14-day persona warm-up (source='warmup', generated by app/synth.py) so the twin has something to
learn from on day one; real events (source='live') are appended as the user works, and the twin
is retrained from whatever is in the database.
"""

from __future__ import annotations

import json
import sqlite3

from .synth import generate

SCHEMA = """
CREATE TABLE IF NOT EXISTS user_segments (
    id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
    day TEXT, start REAL, end REAL, app TEXT, kind TEXT, task TEXT, quality REAL, source TEXT DEFAULT 'warmup');
CREATE INDEX IF NOT EXISTS idx_useg_user ON user_segments(user_id, day);
CREATE TABLE IF NOT EXISTS user_notifications (
    id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
    day TEXT, hour REAL, category TEXT, app TEXT, task TEXT, depth REAL, minutes_in REAL, fatigue REAL,
    action TEXT, opened INTEGER, rabbit INTEGER, away_min REAL, resume_min REAL, cost_min REAL,
    followed_app TEXT, chain TEXT, source TEXT DEFAULT 'warmup');
CREATE INDEX IF NOT EXISTS idx_unot_user ON user_notifications(user_id, day);
"""

N_COLS = ["day", "hour", "category", "app", "task", "depth", "minutes_in", "fatigue", "action", "opened", "rabbit",
          "away_min", "resume_min", "cost_min", "followed_app", "chain"]


def ensure_schema(c: sqlite3.Connection):
    c.executescript(SCHEMA)


def ensure_history(c: sqlite3.Connection, user_id: int, persona: str, seed: int) -> int:
    """Create the warm-up history for an account that has none. Returns the number of events stored."""
    have = c.execute("SELECT COUNT(*) FROM user_notifications WHERE user_id=?", (user_id,)).fetchone()[0]
    if have:
        return have
    segs, notes = generate(persona, seed)
    c.executemany("INSERT INTO user_segments(user_id,day,start,end,app,kind,task,quality,source) VALUES(?,?,?,?,?,?,?,?,'warmup')",
                  [(user_id, s["day"], s["start"], s["end"], s["app"], s["kind"], s["task"], s["quality"]) for s in segs])
    c.executemany(f"INSERT INTO user_notifications(user_id,{','.join(N_COLS)},source) VALUES(?,{','.join('?' * len(N_COLS))},'warmup')",
                  [(user_id, *[json.dumps(n["chain"]) if k == "chain" else n[k] for k in N_COLS]) for n in notes])
    c.commit()
    return len(notes)


def load_history(c: sqlite3.Connection, user_id: int):
    c.row_factory = sqlite3.Row
    segs = [dict(day=r["day"], start=r["start"], end=r["end"], app=r["app"], kind=r["kind"], task=r["task"], quality=r["quality"])
            for r in c.execute("SELECT * FROM user_segments WHERE user_id=? ORDER BY day, start", (user_id,))]
    notes = []
    for r in c.execute("SELECT * FROM user_notifications WHERE user_id=? ORDER BY day, hour", (user_id,)):
        n = {k: r[k] for k in N_COLS}
        n["id"] = f"n{r['id']}"
        n["opened"], n["rabbit"] = bool(n["opened"]), bool(n["rabbit"])
        n["chain"] = json.loads(n["chain"] or "[]")
        notes.append(n)
    return segs, notes


def counts(c: sqlite3.Connection, user_id: int) -> dict:
    out = {}
    for src in ("warmup", "live"):
        out[src] = c.execute("SELECT COUNT(*) FROM user_notifications WHERE user_id=? AND source=?", (user_id, src)).fetchone()[0]
    out["segments"] = c.execute("SELECT COUNT(*) FROM user_segments WHERE user_id=?", (user_id,)).fetchone()[0]
    return out
